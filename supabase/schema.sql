create or replace function public.check_compatibility(p_code1 text, p_code2 text)
returns jsonb
language plpgsql volatile security definer
set search_path = public
as $$
declare
  complementarity constant jsonb := '{
    "1.1": ["2.7", "2.5"], "1.2": ["2.7", "2.4"], "1.3": ["2.6", "2.3"],
    "1.4": ["2.5", "2.3", "2.4", "2.6"], "1.5": ["2.5", "2.2", "2.1", "2.6"],
    "1.6": ["2.4", "2.2", "2.3", "2.5"], "1.7": ["2.5", "2.7", "2.4"],
    "2.1": ["1.5", "1.4", "1.7"], "2.2": ["1.1", "1.5", "1.6"],
    "2.3": ["1.4", "1.7", "1.3"], "2.4": ["1.6", "1.7", "1.4", "1.2"],
    "2.5": ["1.5", "1.4", "1.6", "1.7"], "2.6": ["1.3", "1.5"],
    "2.7": ["1.1", "1.5", "1.6", "1.7"]
  }'::jsonb;
  v_p1 public.profiles%rowtype;
  v_p2 public.profiles%rowtype;
  v_a integer := 0;
  v_p integer := 0;
  v_score double precision;
  v_interpretation text;
  rec record;
  comp text;
  status_other text;
begin
  select * into v_p1 from public.profiles where compatibility_code = trim(p_code1);
  if not found then raise exception 'Коды не найдены'; end if;
  select * into v_p2 from public.profiles where compatibility_code = trim(p_code2);
  if not found then raise exception 'Коды не найдены'; end if;

  if v_p1.archetype_scores is null or v_p2.archetype_scores is null then
    raise exception 'Коды не найдены';
  end if;

  -- Активные архетипы первого против комплементарных статусов второго
  for rec in select key, value::integer as score from jsonb_each_text(v_p1.archetype_scores)
  loop
    if public.archetype_status(rec.score) = 'A' then
      for comp in select jsonb_array_elements_text(coalesce(complementarity -> rec.key, '[]'::jsonb))
      loop
        status_other := public.archetype_status(coalesce((v_p2.archetype_scores ->> comp)::integer, 0));
        if status_other in ('A', 'M') then v_a := v_a + 1;
        elsif status_other = 'P' then v_p := v_p + 1;
        end if;
      end loop;
    end if;
  end loop;

  -- И наоборот
  for rec in select key, value::integer as score from jsonb_each_text(v_p2.archetype_scores)
  loop
    if public.archetype_status(rec.score) = 'A' then
      for comp in select jsonb_array_elements_text(coalesce(complementarity -> rec.key, '[]'::jsonb))
      loop
        status_other := public.archetype_status(coalesce((v_p1.archetype_scores ->> comp)::integer, 0));
        if status_other in ('A', 'M') then v_a := v_a + 1;
        elsif status_other = 'P' then v_p := v_p + 1;
        end if;
      end loop;
    end if;
  end loop;

  if v_a = 7 and v_p = 0 then v_interpretation := 'Максимальная прочность союза';
  elsif v_a = 0 and v_p = 7 then v_interpretation := 'Минимальная прочность (развал)';
  elsif v_p > 0 and v_a > v_p then v_interpretation := 'База есть, но есть очаги конфликтов';
  elsif v_a < v_p then v_interpretation := 'Союз временный (против больше чем за)';
  else v_interpretation := 'Средняя совместимость';
  end if;

  if v_a >= 3 then
    v_interpretation := v_interpretation || '. Отношения имеют тенденцию к сохранению';
  end if;

  if v_a + v_p > 0 then
    v_score := round((v_a::numeric / (v_a + v_p)) * 100, 1);
  else
    v_score := 50.0;
  end if;

  insert into public.couples (user1_code, user2_code, compatibility_index, a_count, p_count, score, interpretation)
  values (trim(p_code1), trim(p_code2), v_a || '/' || v_p, v_a, v_p, v_score, v_interpretation);

  return jsonb_build_object(
    'user1', jsonb_build_object('login', v_p1.login, 'code', trim(p_code1)),
    'user2', jsonb_build_object('login', v_p2.login, 'code', trim(p_code2)),
    'index', v_a || '/' || v_p,
    'A_count', v_a,
    'P_count', v_p,
    'score', v_score,
    'interpretation', v_interpretation
  );
end;
$$;

