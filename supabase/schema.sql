-- Проверка «текущий пользователь — админ» (security definer, чтобы не упереться в RLS)
create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and is_active
  );
$$;

-- Статус архетипа по баллам: A — активный, M — средний, N — неопределённый, P — пассивный
create or replace function public.archetype_status(p_score integer)
returns text
language sql immutable
as $$
  select case
    when p_score >= 4 then 'A'
    when p_score = 3 then 'M'
    when p_score = 2 then 'N'
    else 'P'
  end;
$$;

-- Генерация кода совместимости в формате PSY-YYYYMMDD-XXXXXXXXXXXX
create or replace function public.generate_compatibility_code()
returns text
language sql volatile
as $$
  select 'PSY-' || to_char(now(), 'YYYYMMDD') || '-' ||
         upper(substr(md5(random()::text || clock_timestamp()::text), 1, 12));
$$;

-- Проверка занятости логина (используется до регистрации)
create or replace function public.login_exists(p_login text)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles where lower(login) = lower(trim(p_login))
  );
$$;

