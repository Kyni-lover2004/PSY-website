create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, login, gender, orientation)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'login'), ''), 'user_' || left(new.id::text, 8)),
    nullif(new.raw_user_meta_data ->> 'gender', ''),
    nullif(new.raw_user_meta_data ->> 'orientation', '')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ============================================================
-- 4. ЛОГИКА ТЕСТА: подсчёт баллов по каждому классу-архетипу
-- ============================================================

-- Завершение теста. p_answers: [{"question_id": 1, "value": true}, ...]
-- Каждый ответ «Да» добавляет 1 балл архетипу, к которому привязан вопрос.
-- Балл на архетип ограничен 5. Всегда возвращаются все 7 классов пола.
create or replace function public.complete_test(
  p_gender text,
  p_answers jsonb,
  p_session_id text default null
)
returns jsonb
language plpgsql volatile security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_prefix text;
  v_scores jsonb;
  v_statuses jsonb;
  v_code text;
  v_main_code text;
  v_main_name text;
  v_total integer;
  v_login text;
  v_telegram text;
begin
  if v_user_id is null then
    raise exception 'Требуется авторизация';
  end if;

  if p_gender not in ('male', 'female') then
    raise exception 'Неверный параметр пола';
  end if;

  if p_answers is null or jsonb_typeof(p_answers) <> 'array' or jsonb_array_length(p_answers) = 0 then
    raise exception 'Ответы не переданы';
  end if;

  v_prefix := case when p_gender = 'male' then '1.' else '2.' end;

  -- Журналируем ответы
  insert into public.answers (user_id, session_id, question_id, value)
  select v_user_id, p_session_id, (a ->> 'question_id')::integer, (a ->> 'value')::boolean
  from jsonb_array_elements(p_answers) a
  where (a ->> 'question_id') ~ '^\d+$';

  -- Баллы по каждому классу: считаем «Да» по архетипу вопроса, максимум 5,
  -- отсутствующие классы заполняем нулями
  with ans as (
    select (a ->> 'question_id')::integer as question_id,
           (a ->> 'value')::boolean as value
    from jsonb_array_elements(p_answers) a
    where (a ->> 'question_id') ~ '^\d+$'
  ),
  per_class as (
    select q.archetype_code as code, least(count(*), 5)::integer as score
    from ans
    join public.questions q
      on q.id = ans.question_id
     and q.gender_type = p_gender
     and q.is_active
    where ans.value
    group by q.archetype_code
  ),
  full_set as (
    select a.code, coalesce(pc.score, 0) as score
    from public.archetypes a
    left join per_class pc on pc.code = a.code
    where a.code like v_prefix || '%'
  )
  select jsonb_object_agg(code, score),
         jsonb_object_agg(code, public.archetype_status(score)),
         sum(score)::integer
    into v_scores, v_statuses, v_total
  from full_set;

  -- Ведущий архетип — класс с максимальным баллом
  select fs.key, a.name
    into v_main_code, v_main_name
  from jsonb_each_text(v_scores) fs
  join public.archetypes a on a.code = fs.key
  order by fs.value::integer desc, fs.key
  limit 1;

  -- Обновляем профиль; код совместимости генерируем один раз
  select compatibility_code, login, telegram
    into v_code, v_login, v_telegram
  from public.profiles where id = v_user_id;

  if v_code is null then
    loop
      v_code := public.generate_compatibility_code();
      exit when not exists (select 1 from public.profiles where compatibility_code = v_code);
    end loop;
  end if;

  update public.profiles
     set archetype_scores = v_scores,
         active_archetypes = v_statuses,
         gender = p_gender,
         compatibility_code = v_code
   where id = v_user_id;

  -- Сохраняем запись результата
  insert into public.test_results (
    user_id, user_login, user_telegram, test_type, gender,
    total_score, archetype_result, archetype_name, scores_breakdown, result_text
  ) values (
    v_user_id, v_login, v_telegram, 'archetype', p_gender,
    coalesce(v_total, 0), v_main_code, v_main_name, v_scores,
    'Архетип: ' || coalesce(v_main_name, v_main_code, 'Не определён')
  );

  return jsonb_build_object(
    'session_id', p_session_id,
    'compatibility_code', v_code,
    'scores', v_scores,
    'active_archetypes', v_statuses,
    'archetype_code', v_main_code,
    'archetype_name', v_main_name
  );
end;
$$;

-- Результаты по коду совместимости (доступно всем, у кого есть код)
create or replace function public.get_profile_by_code(p_code text)
returns jsonb
language plpgsql stable security definer
set search_path = public
as $$
declare
  v_profile public.profiles%rowtype;
  v_archetypes jsonb;
begin
  select * into v_profile
  from public.profiles
  where compatibility_code = trim(p_code);

  if not found or v_profile.archetype_scores is null then
    return null;
  end if;

  select jsonb_agg(item order by (item ->> 'score')::integer desc, item ->> 'code')
    into v_archetypes
  from (
    select jsonb_build_object(
      'code', s.key,
      'name', coalesce(a.name, s.key),
      'score', s.value::integer,
      'status', coalesce(v_profile.active_archetypes ->> s.key, public.archetype_status(s.value::integer)),
      'color', coalesce(a.color, '#999'),
      'chakra', a.chakra,
      'description', coalesce(a.description, ''),
      'strengths', coalesce(a.strengths, ''),
      'weaknesses', coalesce(a.weaknesses, '')
    ) as item
    from jsonb_each_text(v_profile.archetype_scores) s
    left join public.archetypes a on a.code = s.key
  ) t;

  return jsonb_build_object(
    'compatibility_code', v_profile.compatibility_code,
    'gender', v_profile.gender,
    'archetypes', coalesce(v_archetypes, '[]'::jsonb)
  );
end;
$$;

-- Привязка результатов, полученных по коду, к текущему аккаунту
create or replace function public.save_results_to_account(p_code text)
returns jsonb
language plpgsql volatile security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_source public.profiles%rowtype;
begin
  if v_user_id is null then
    raise exception 'Требуется авторизация';
  end if;

  select * into v_source
  from public.profiles
  where compatibility_code = trim(p_code);

  if not found then
    raise exception 'Результаты не найдены';
  end if;

  if v_source.id <> v_user_id then
    -- Код переносится на текущий аккаунт (у источника освобождаем уникальное поле)
    update public.profiles set compatibility_code = null where id = v_source.id;
  end if;

  update public.profiles
     set compatibility_code = v_source.compatibility_code,
         archetype_scores = v_source.archetype_scores,
         active_archetypes = v_source.active_archetypes,
         gender = coalesce(v_source.gender, gender),
         orientation = coalesce(v_source.orientation, orientation)
   where id = v_user_id;

  return jsonb_build_object(
    'success', true,
    'compatibility_code', v_source.compatibility_code,
    'archetype_scores', v_source.archetype_scores
  );
end;
$$;

