-- Профили пользователей (создаются автоматически триггером при регистрации)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  login text not null unique,
  telegram text,
  gender text check (gender in ('male', 'female')),
  orientation text,
  role text not null default 'user' check (role in ('user', 'admin')),
  compatibility_code text unique,
  archetype_scores jsonb,
  active_archetypes jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Справочник архетипов (14 классов: 1.x — мужские, 2.x — женские)
create table if not exists public.archetypes (
  code text primary key,
  name text not null,
  color text,
  chakra integer,
  description text,
  strengths text,
  weaknesses text
);

-- Вопросы теста на архетипы.
-- КАЖДЫЙ вопрос привязан к своему классу (archetype_code):
-- ответ «Да» добавляет 1 балл именно этому архетипу.
create table if not exists public.questions (
  id integer generated by default as identity primary key,
  gender_type text not null check (gender_type in ('male', 'female')),
  text text not null,
  archetype_code text not null references public.archetypes(code),
  order_index integer not null,
  is_active boolean not null default true
);

-- Сырые ответы (журнал прохождений)
create table if not exists public.answers (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade,
  session_id text,
  question_id integer not null references public.questions(id),
  value boolean not null,
  created_at timestamptz not null default now()
);

-- Результаты тестов
create table if not exists public.test_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  user_login text not null,
  user_telegram text,
  test_type text not null,
  gender text,
  total_score double precision default 0,
  archetype_result text,
  archetype_name text,
  scores_breakdown jsonb,
  result_text text,
  completed_at timestamptz not null default now()
);

-- Заявки на консультацию
create table if not exists public.consultations (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  name text not null,
  telegram text,
  category text,
  topic text,
  request_text text not null,
  status text not null default 'new' check (status in ('new', 'in_progress', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Журнал проверок совместимости
create table if not exists public.couples (
  id bigint generated by default as identity primary key,
  user1_code text not null,
  user2_code text not null,
  compatibility_index text,
  a_count integer default 0,
  p_count integer default 0,
  score double precision default 0,
  interpretation text,
  created_at timestamptz not null default now()
);

-- Конструктор дополнительных тестов (админ-панель)
create table if not exists public.tests (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  category text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.test_questions (
  id bigint generated by default as identity primary key,
  test_id bigint not null references public.tests(id) on delete cascade,
  text text not null,
  order_index integer not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.answer_options (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.test_questions(id) on delete cascade,
  text text not null,
  score double precision not null default 0,
  order_index integer not null,
  is_active boolean not null default true
);

-- Комментарии
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  user_login text not null,
  content text not null,
  target_type text not null default 'general',
  target_id bigint,
  parent_id bigint references public.comments(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  is_deleted boolean not null default false
);

create index if not exists idx_questions_gender on public.questions (gender_type, order_index);
create index if not exists idx_test_results_user on public.test_results (user_id);
create index if not exists idx_consultations_status on public.consultations (status);
create index if not exists idx_comments_target on public.comments (target_type, target_id);

